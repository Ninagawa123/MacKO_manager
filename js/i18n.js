function t(key) {
  const lang = localStorage.getItem("mackomgr.lang") || "ja";
  return (I18N[lang] && I18N[lang][key]) || I18N.ja[key] || key;
}

function applyI18n() {
  document.documentElement.lang = localStorage.getItem("mackomgr.lang") || "ja";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
}
